-- =====================================================================
-- CU-01 (cambio) · Catálogo de unidades de medida para el catálogo de conceptos.
-- La unidad de cada concepto se elige de una lista desplegable con estas unidades.
-- Script INCREMENTAL: no borra datos y se puede ejecutar más de una vez.
-- =====================================================================
CREATE TABLE IF NOT EXISTS catalogo_unidades_medida (
  id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave   VARCHAR(20) NOT NULL UNIQUE,
  nombre  VARCHAR(60) NOT NULL,
  activo  BOOLEAN NOT NULL DEFAULT true
);

INSERT INTO catalogo_unidades_medida (clave, nombre) VALUES
  ('m',     'Metro lineal'),
  ('m2',    'Metro cuadrado'),
  ('m3',    'Metro cúbico'),
  ('km',    'Kilómetro'),
  ('kg',    'Kilogramo'),
  ('ton',   'Tonelada'),
  ('l',     'Litro'),
  ('pza',   'Pieza'),
  ('lote',  'Lote'),
  ('jgo',   'Juego'),
  ('sal',   'Salida'),
  ('viaje', 'Viaje'),
  ('m3-km', 'Metro cúbico-kilómetro'),
  ('hr',    'Hora'),
  ('jor',   'Jornal'),
  ('día',   'Día'),
  ('mes',   'Mes')
ON CONFLICT (clave) DO NOTHING;

-- Unidades que ya se usan en conceptos capturados antes de este cambio: se agregan para no perderlas.
INSERT INTO catalogo_unidades_medida (clave, nombre)
SELECT DISTINCT unidad_medida, unidad_medida FROM catalogo_conceptos
 WHERE unidad_medida IS NOT NULL AND btrim(unidad_medida) <> ''
ON CONFLICT (clave) DO NOTHING;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'obras_app') THEN
    EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON catalogo_unidades_medida TO obras_app';
    EXECUTE 'GRANT USAGE, SELECT, UPDATE ON SEQUENCE catalogo_unidades_medida_id_seq TO obras_app';
    EXECUTE 'ALTER TABLE catalogo_unidades_medida ENABLE ROW LEVEL SECURITY';
    EXECUTE 'DROP POLICY IF EXISTS app_total ON catalogo_unidades_medida';
    EXECUTE 'CREATE POLICY app_total ON catalogo_unidades_medida FOR ALL TO obras_app USING (true) WITH CHECK (true)';
  END IF;
END $$;
