-- 1. Catálogo de tipos de nota
CREATE TABLE IF NOT EXISTS catalogo_tipos_nota (
  id           SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(50) NOT NULL UNIQUE,
  descripcion  TEXT
);
INSERT INTO catalogo_tipos_nota (id, nombre, descripcion) VALUES
  (1, 'Apertura',    'Apertura de la bitácora y datos generales de la obra'),
  (2, 'Instrucción', 'Instrucción u orden de trabajo'),
  (3, 'Solicitud',   'Solicitud de información, aprobación o cambio'),
  (4, 'Avance',      'Registro de avance o de trabajos ejecutados'),
  (5, 'Incidencia',  'Incidencia, problema o situación extraordinaria'),
  (6, 'Cierre',      'Cierre de la bitácora'),
  (7, 'Otra',        'Cualquier otro asunto')
ON CONFLICT (id) DO NOTHING;
SELECT setval(pg_get_serial_sequence('catalogo_tipos_nota', 'id'), (SELECT max(id) FROM catalogo_tipos_nota));

-- 2. Contador de folios por obra (un folio nunca se reutiliza, aunque se borre la nota)
ALTER TABLE obras ADD COLUMN IF NOT EXISTS ultimo_folio_bitacora INTEGER NOT NULL DEFAULT 0;

-- 3. Columnas nuevas de la nota
ALTER TABLE notas_bitacora ADD COLUMN IF NOT EXISTS folio INTEGER;
ALTER TABLE notas_bitacora ADD COLUMN IF NOT EXISTS tipo_id SMALLINT REFERENCES catalogo_tipos_nota(id);
ALTER TABLE notas_bitacora ADD COLUMN IF NOT EXISTS nota_relacionada_id UUID REFERENCES notas_bitacora(id) ON DELETE SET NULL;
ALTER TABLE notas_bitacora ADD COLUMN IF NOT EXISTS fecha_modificacion TIMESTAMPTZ;

-- Notas que ya existían: folio por orden de fecha dentro de cada obra y tipo «Otra».
WITH numeradas AS (
  SELECT n.id,
         COALESCE((SELECT max(m.folio) FROM notas_bitacora m WHERE m.obra_id = n.obra_id), 0)
           + row_number() OVER (PARTITION BY n.obra_id ORDER BY n.fecha_nota, n.id) AS folio
    FROM notas_bitacora n
   WHERE n.folio IS NULL OR n.folio = 0
)
UPDATE notas_bitacora n SET folio = numeradas.folio FROM numeradas WHERE n.id = numeradas.id;
UPDATE notas_bitacora SET tipo_id = 7 WHERE tipo_id IS NULL;
UPDATE obras o
   SET ultimo_folio_bitacora = GREATEST(o.ultimo_folio_bitacora,
                                        COALESCE((SELECT max(folio) FROM notas_bitacora n WHERE n.obra_id = o.id), 0));

ALTER TABLE notas_bitacora ALTER COLUMN folio SET DEFAULT 0;
ALTER TABLE notas_bitacora ALTER COLUMN folio SET NOT NULL;
ALTER TABLE notas_bitacora ALTER COLUMN tipo_id SET DEFAULT 7;
ALTER TABLE notas_bitacora ALTER COLUMN tipo_id SET NOT NULL;
ALTER TABLE notas_bitacora DROP CONSTRAINT IF EXISTS uq_notas_obra_folio;
ALTER TABLE notas_bitacora ADD CONSTRAINT uq_notas_obra_folio UNIQUE (obra_id, folio);
ALTER TABLE notas_bitacora DROP CONSTRAINT IF EXISTS ck_nota_no_se_relaciona_consigo;
ALTER TABLE notas_bitacora ADD CONSTRAINT ck_nota_no_se_relaciona_consigo
  CHECK (nota_relacionada_id IS NULL OR nota_relacionada_id <> id);
CREATE INDEX IF NOT EXISTS ix_notas_tipo        ON notas_bitacora (tipo_id);
CREATE INDEX IF NOT EXISTS ix_notas_relacionada ON notas_bitacora (nota_relacionada_id) WHERE nota_relacionada_id IS NOT NULL;

-- 4. El folio lo asigna la base de datos al insertar (consecutivo por obra, sin choques entre usuarios).
CREATE OR REPLACE FUNCTION fn_asignar_folio_bitacora() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.folio IS NULL OR NEW.folio = 0 THEN
    UPDATE obras SET ultimo_folio_bitacora = ultimo_folio_bitacora + 1
     WHERE id = NEW.obra_id
     RETURNING ultimo_folio_bitacora INTO NEW.folio;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_nota_folio ON notas_bitacora;
CREATE TRIGGER trg_nota_folio
  BEFORE INSERT ON notas_bitacora
  FOR EACH ROW EXECUTE FUNCTION fn_asignar_folio_bitacora();

-- 5. Firmas: historial de decisiones de cada rol firmante sobre la nota.
--    'Pendiente' marca un reinicio (nota corregida y reenviada, o corrección del administrador).
CREATE TABLE IF NOT EXISTS firmas_notas_bitacora (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nota_bitacora_id      UUID NOT NULL REFERENCES notas_bitacora(id) ON DELETE CASCADE,
  usuario_firmante_id   UUID NOT NULL REFERENCES usuarios(id),
  rol_firmante          VARCHAR(40) NOT NULL
                          CHECK (rol_firmante IN ('Residente', 'Supervisor', 'Superintendente Contratista')),
  decision              VARCHAR(20) NOT NULL CHECK (decision IN ('Firmada', 'Rechazada', 'Pendiente')),
  fecha_firma           TIMESTAMPTZ NOT NULL DEFAULT now(),
  comentarios           TEXT
);
CREATE INDEX IF NOT EXISTS ix_firmas_nota     ON firmas_notas_bitacora (nota_bitacora_id);
CREATE INDEX IF NOT EXISTS ix_firmas_firmante ON firmas_notas_bitacora (usuario_firmante_id);

-- 6. Seguridad en Supabase (solo si existe el rol de la aplicación)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'obras_app') THEN
    EXECUTE 'GRANT SELECT ON catalogo_tipos_nota TO obras_app';
    EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON firmas_notas_bitacora TO obras_app';
    EXECUTE 'ALTER TABLE catalogo_tipos_nota ENABLE ROW LEVEL SECURITY';
    EXECUTE 'DROP POLICY IF EXISTS app_lectura ON catalogo_tipos_nota';
    EXECUTE 'CREATE POLICY app_lectura ON catalogo_tipos_nota FOR SELECT TO obras_app USING (true)';
    EXECUTE 'ALTER TABLE firmas_notas_bitacora ENABLE ROW LEVEL SECURITY';
    EXECUTE 'DROP POLICY IF EXISTS app_total ON firmas_notas_bitacora';
    EXECUTE 'CREATE POLICY app_total ON firmas_notas_bitacora FOR ALL TO obras_app USING (true) WITH CHECK (true)';
  END IF;
END $$;
